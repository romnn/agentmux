#!/usr/bin/env bash
# Generate the codex app-server protocol types from the pinned codex CLI, with the pinned progeny.
#
# usage: generate.sh <output.rs>
#
# Reads the CLI's own JSON Schema (`codex app-server generate-json-schema`), keeps the types
# agentmux exchanges (roots.json) and what they reference (wrap.jq), and has progeny render them
# as one module.
# The method names of every notification and request the server can send are appended, so the
# driver can tell a method it ignores on purpose from one this schema never had.
#
# Both inputs are pinned beside this script, and nothing here changes a pin.
# codex-version names the CLI release, which must be the `codex` on PATH.
# progeny-rev names the progeny commit, which is built once into a cache directory unless PROGENY
# names a binary.
# To move to another codex, install it, write its version into codex-version, and run
# `task codegen:app-server`.
#
# What progeny reports for codex-cli 0.159.3, none of which agentmux depends on:
#
# - `UserInput` is a union without a discriminator whose `image` branch nests an `anyOf`, which
#   progeny reads as overlapping branches, so the type is plain JSON.
#   agentmux builds the branch it sends, `TextUserInput`, as its own generated type and encodes it
#   into that slot.
# - `minimum` and `minLength` are not expressed by any Rust type, so those values are accepted
#   unchecked.
# - A property that may be both absent and null collapses to `None` in either case.
# - `default` is not derived for a struct that holds an enum, even under `Option`, so requests
#   spell every field out.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out="$1"
codex_version="$(cat "$here/codex-version")"
progeny_rev="$(cat "$here/progeny-rev")"

installed="$(codex --version | awk '{print $NF}')"
if [ "$installed" != "$codex_version" ]; then
  echo "generate.sh: codex-cli $installed is on PATH, but the protocol types are pinned to" \
    "$codex_version (codex-version); install that release, or move the pin deliberately" >&2
  exit 1
fi

# An isolated Codex consultation runs over `codex exec` only because the app-server cannot skip the
# user's configuration.
# The release that adds that flag is the one to change `Delegate::app_server_settings` for, so a
# bump to it stops here rather than passing unnoticed.
if codex app-server --help 2>&1 | grep -q -- '--ignore-user-config'; then
  echo "generate.sh: codex app-server $installed accepts --ignore-user-config, so isolated" \
    "consultations can now be driven and steered: pass it in Delegate::app_server_settings," \
    "drop the isolation condition there, then remove this check" >&2
  exit 1
fi

progeny="${PROGENY:-}"
if [ -z "$progeny" ]; then
  root="${XDG_CACHE_HOME:-$HOME/.cache}/agentmux/progeny-$progeny_rev"
  progeny="$root/bin/progeny"
  if [ ! -x "$progeny" ]; then
    cargo install --locked --quiet --git https://github.com/romnn/progeny --rev "$progeny_rev" \
      progeny-cli --root "$root" >&2
  fi
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

codex app-server generate-json-schema --out "$work/schema" >/dev/null
bundle="$work/schema/codex_app_server_protocol.schemas.json"
jq --argjson roots "$(cat "$here/roots.json")" --arg version "$codex_version" \
  -f "$here/wrap.jq" "$bundle" >"$work/openapi.json"
"$progeny" "$work/openapi.json" --config "$here/progeny.toml" --out-dir "$work/out" >&2

# The `method` of every branch of one of the bundle's unions, as Rust string literals.
methods() {
  jq -r --arg union "$1" \
    '[.definitions[$union] | .. | objects | select(has("method")) | .method.enum[]?]
     | unique[] | "    \"\(.)\","' "$bundle"
}

{
  printf '// @generated by `task codegen:app-server` from codex-cli %s and progeny %s. Do not edit.\n' \
    "$codex_version" "$progeny_rev"
  cat "$work/out/progeny.rs"
  printf '\n/// Every notification method codex-cli %s can send.\n' "$codex_version"
  printf 'pub const SERVER_NOTIFICATIONS: &[&str] = &[\n'
  methods ServerNotification
  printf '];\n\n/// Every request method codex-cli %s can send.\n' "$codex_version"
  printf 'pub const SERVER_REQUESTS: &[&str] = &[\n'
  methods ServerRequest
  printf '];\n'
} >"$out"
# Formatted as `cargo fmt` would leave it, so formatting the workspace never changes the file and
# the check compares like with like.
rustfmt --edition 2024 "$out"
